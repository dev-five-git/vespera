//! How a relation's target `Schema` converts from its `Model`, read from the
//! `schema_type!` invocation that generates it (its `omit` / `pick` / `add`
//! decide between `From` and `from_model`, not the target `Model` alone).

use super::{source_column_read, source_field_named};
use crate::schema_macro::field_selection::selected_rust_names;
use crate::schema_macro::input::SchemaTypeInput;
use crate::schema_macro::module_scope::readable_from;
use crate::schema_macro::seaorm::{
    convert_relation_type_to_schema_with_info, has_sea_orm_database_default,
    has_sea_orm_primary_key, primary_key_count,
};
use crate::schema_macro::transformation::should_skip_field;
use crate::schema_macro::type_utils::{SeaOrmRelationKind, is_seaorm_model, seaorm_relation_kind};

/// The conversion a generated target `Schema` offers.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum TargetShape {
    /// `async fn from_model(model, db)`: the DTO keeps relation fields.
    FromModel,
    /// `From<Model>`: no relation fields.
    From,
    /// Neither (`add` / `multipart`).
    Neither,
}

/// The shape of `schema_name`, generated by a `schema_type!` in the module
/// `module` (absolute, `crate::..`) from the `Model` defined as `model_def`.
/// `None` when the module holds no such invocation (a hand-written
/// `Schema`, or one generated elsewhere).
///
/// Memoised across invocations while every file the module lookup read is
/// unchanged (`file_cache::Tracked`): each relation otherwise re-parsed its
/// target module and every `schema_type!` input in it.
pub(super) fn target_shape(
    module: &[String],
    schema_name: &str,
    model_def: &str,
) -> Option<TargetShape> {
    type Key = (
        Option<crate::schema_macro::crate_layout::CrateLayout>,
        Vec<String>,
        String,
        String,
    );
    type Memo = std::collections::HashMap<
        Key,
        crate::schema_macro::file_cache::Tracked<Option<TargetShape>>,
    >;
    thread_local! {
        static MEMO: std::cell::RefCell<Memo> = std::cell::RefCell::new(Memo::new());
    }
    let key: Key = (
        crate::schema_macro::crate_layout::crate_layout(),
        module.to_vec(),
        schema_name.to_owned(),
        model_def.to_owned(),
    );
    let hit = MEMO.with(|memo| {
        memo.borrow_mut()
            .get_mut(&key)
            .and_then(crate::schema_macro::file_cache::Tracked::get)
    });
    if let Some(shape) = hit {
        return shape;
    }
    let entry = crate::schema_macro::file_cache::Tracked::compute(|| {
        compute_target_shape(module, schema_name, model_def)
    });
    let shape = *entry.peek();
    MEMO.with(|memo| memo.borrow_mut().insert(key, entry));
    shape
}

fn compute_target_shape(
    module: &[String],
    schema_name: &str,
    model_def: &str,
) -> Option<TargetShape> {
    let items = crate::schema_macro::module_scope::module_items(module)?;
    let input = items.iter().find_map(|item| {
        let syn::Item::Macro(item) = item else {
            return None;
        };
        // A `#[cfg]` twin the build drops is not the invocation the DTO came from
        // (R31-SM2-01): the other item scans of this crate skip it too.
        if crate::schema_macro::cfg_eval::compiled_out(&item.attrs) {
            return None;
        }
        (item.mac.path.segments.last()?.ident == "schema_type")
            .then(|| syn::parse2::<SchemaTypeInput>(item.mac.tokens.clone()).ok())?
            .filter(|input| input.new_type == schema_name)
    })?;
    if input.add.is_some() || input.multipart {
        return Some(TargetShape::Neither);
    }
    // The source the generated DTO reads, not the target module's `Model`
    // alone: `generate_type` builds the DTO from that struct.
    let (source_module, source_def) = source_of(&input.source_type, module, model_def)?;
    let model = crate::schema_macro::file_cache::parse_struct_cached(&source_def).ok()?;
    // The same name resolution `generate_type` applies (the DTO was validated
    // when it was generated; a name that selects nothing is kept as written).
    let omit = selected_rust_names(&model, input.omit.as_deref().unwrap_or_default());
    let pick = selected_rust_names(&model, input.pick.as_deref().unwrap_or_default());
    // The `generate_type` rules: relations survive `omit` / `pick`, HasMany
    // only when `pick`ed; every other kept field must be readable from the
    // module the DTO is emitted in (a private field of another module makes
    // `generate_type` leave both impls out).
    // `omit_default` drops a primary key too (`generate_type`'s rule, through
    // `has_sea_orm_primary_key` with the model's key count): the same predicate
    // here, or a private dropped key made the shape `Neither` (R20-SM2-01).
    let pk_count = primary_key_count(&model.fields);
    let mut has_relation = false;
    let mut all_readable = true;
    // The relations `generate_type` emits (adapters included: their loads read
    // source columns too, R21-SM2-L1 and R22-SM2-M1).
    let mut relations = Vec::new();
    for field in &model.fields {
        let name = field
            .ident
            .as_ref()
            .map(|ident| crate::parser::strip_raw_prefix_owned(ident.to_string()))
            .unwrap_or_default();
        if should_skip_field(&name, &omit, &pick)
            || (input.omit_default
                && (has_sea_orm_database_default(&field.attrs)
                    || has_sea_orm_primary_key(&field.attrs, &field.ty, pk_count)))
        {
            continue;
        }
        match seaorm_relation_kind(&field.ty) {
            // An un-picked HasMany is dropped by `generate_type` before its
            // readability is looked at.
            Some(SeaOrmRelationKind::HasMany) if !pick.contains(&name) => {}
            // A relation `generate_type` cannot convert is dropped, so it is
            // no relation the DTO loads (R25-SM2-02): only a converted one
            // makes the shape `FromModel`.
            Some(_) => {
                if let Some(ident) = field.ident.clone()
                    && let Some((_, rel)) = convert_relation_type_to_schema_with_info(
                        &field.ty,
                        &field.attrs,
                        &model,
                        &source_module,
                        ident,
                    )
                {
                    has_relation = true;
                    relations.push(rel);
                }
            }
            None => {
                all_readable &= readable_from(&field.vis, &source_module, Some(module));
            }
        }
    }
    // The source column each emitted load reads must be readable from the DTO
    // module, even when `omit` removed it from the DTO (as `generate_type`).
    for rel in &relations {
        if let Some(column) = source_column_read(rel, &model.fields)
            && let Some(source) = source_field_named(&model.fields, &column)
        {
            all_readable &= readable_from(&source.vis, &source_module, Some(module));
        }
    }
    // `From` needs no relation field and every field readable; `from_model`
    // needs relation fields, a SeaORM source and every field readable.
    let is_model = is_seaorm_model(&model);
    Some(match (has_relation, all_readable) {
        (true, true) if is_model => TargetShape::FromModel,
        (false, true) => TargetShape::From,
        _ => TargetShape::Neither,
    })
}

/// The `Model` a `schema_type!` source names, with its module: the module's
/// own `Model` (`model_def`, the struct the caller read), or a `crate::` path
/// to another one. Other spellings are not resolved here (`None`: the caller
/// falls back to the circular analysis).
fn source_of(
    source: &syn::Type,
    module: &[String],
    model_def: &str,
) -> Option<(Vec<String>, String)> {
    let syn::Type::Path(path) = source else {
        return None;
    };
    if path.qself.is_some() {
        return None;
    }
    let names: Vec<String> = path
        .path
        .segments
        .iter()
        .map(|segment| crate::parser::strip_raw_prefix_owned(segment.ident.to_string()))
        .collect();
    let names: Vec<&str> = names.iter().map(String::as_str).collect();
    if matches!(names.as_slice(), ["Model"] | ["self", "Model"]) {
        return Some((module.to_vec(), model_def.to_string()));
    }
    let [crate_root, .., _] = names.as_slice() else {
        return None;
    };
    if *crate_root != "crate" {
        return None;
    }
    let owner = names[..names.len() - 1]
        .iter()
        .map(|s| (*s).to_string())
        .collect();
    let definition =
        crate::schema_macro::file_cache::get_struct_from_schema_path(&names.join("::"))?
            .definition
            .clone();
    Some((owner, definition))
}

#[cfg(test)]
mod tests {
    use rstest::rstest;

    use super::*;

    /// The target module's `Model`: a relation (`profile`), so its `Schema`
    /// would get `from_model` when generated from it.
    const USER_MODEL: &str = r#"#[sea_orm(table_name = "user")] pub struct Model { pub id: i32, pub profile: HasOne<super::profile::Entity> }"#;

    /// A crate whose `models::user` generates `Schema` from `source`, with a
    /// `legacy::Model` written as `legacy`.
    fn write_crate(dir: &std::path::Path, legacy: &str, source: &str, args: &str) {
        let files = [
            (
                "src/lib.rs",
                "pub mod legacy;\npub mod models;\n".to_string(),
            ),
            ("src/legacy.rs", legacy.to_string()),
            ("src/models.rs", "pub mod user;\n".to_string()),
            (
                "src/models/user.rs",
                format!("vespera::schema_type!(Schema from {source}{args});\n{USER_MODEL}\n"),
            ),
        ];
        for (path, content) in files {
            let path = dir.join(path);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, content).unwrap();
        }
    }

    /// The shape follows the struct the `schema_type!` reads, not the
    /// target module's `Model`: a source without relations gets `From`
    /// (the `models::user::Model` relation used to predict `from_model`,
    /// which does not exist: E0599), and a private field of another module
    /// leaves both impls out.
    #[rstest]
    #[case::legacy_without_relations(
        "pub struct Model { pub id: i32 }",
        "crate::legacy::Model",
        TargetShape::From
    )]
    #[case::private_field_of_another_module(
        "pub struct Model { id: i32 }",
        "crate::legacy::Model",
        TargetShape::Neither
    )]
    #[case::own_model_with_relation(
        "pub struct Model { pub id: i32 }",
        "Model",
        TargetShape::FromModel
    )]
    // R20-SM2-01 (round 20): fields `generate_type` drops are not counted.
    // An un-picked HasMany (private, so unreadable here) is dropped ...
    #[case::unpicked_private_has_many(
        "pub struct Model { pub id: i32, memos: HasMany<super::memo::Entity> }",
        "crate::legacy::Model",
        TargetShape::From
    )]
    // ... and so is an `omit_default` primary key (private, so unreadable).
    #[case::omit_default_private_primary_key(
        "pub struct Model { #[sea_orm(primary_key)] id: i32, pub name: String }",
        "crate::legacy::Model",
        TargetShape::From
    )]
    // R25-SM2-02: a relation `generate_type` cannot convert (a non-path
    // target) is dropped with no `from_model` load, so the shape is `From`.
    #[case::unconvertible_relation_is_dropped(
        "#[sea_orm(table_name = \"memos\")]\npub struct Model { pub id: i32, pub profile: HasOne<&'static str> }",
        "crate::legacy::Model",
        TargetShape::From
    )]
    fn shape_follows_the_schema_type_source(
        #[case] legacy: &str,
        #[case] source: &str,
        #[case] expected: TargetShape,
    ) {
        let args = if legacy.contains("primary_key") {
            ", omit_default"
        } else {
            ""
        };
        let dir = tempfile::TempDir::new().unwrap();
        write_crate(dir.path(), legacy, source, args);
        let _manifest = crate::env_access::test_env::set_var("CARGO_MANIFEST_DIR", dir.path());
        let module: Vec<String> = ["crate", "models", "user"].map(String::from).to_vec();
        assert_eq!(
            compute_target_shape(&module, "Schema", USER_MODEL),
            Some(expected)
        );
    }

    /// R21-SM2-L1 (round 21): the relation's load reads its FK from the source
    /// even when `omit` drops that field, so a private FK leaves both impls out
    /// (as `generate_type` decides). A public FK keeps `from_model`.
    #[rstest]
    #[case::private_fk_read_by_the_load("", TargetShape::Neither)]
    #[case::public_fk_is_readable("pub ", TargetShape::FromModel)]
    fn omitted_fk_of_a_relation_follows_its_readability(
        #[case] fk_vis: &str,
        #[case] expected: TargetShape,
    ) {
        let legacy = format!(
            "#[sea_orm(table_name = \"memos\")]\npub struct Model {{\n    pub id: i32,\n    {fk_vis}owner_id: i32,\n    #[sea_orm(belongs_to = \"super::user::Entity\", from = \"owner_id\", to = \"id\", relation_enum = \"Owner\")]\n    pub owner: BelongsTo<super::user::Entity>,\n}}"
        );
        let dir = tempfile::TempDir::new().unwrap();
        write_crate(
            dir.path(),
            &legacy,
            "crate::legacy::Model",
            ", omit = [\"owner_id\"]",
        );
        let _manifest = crate::env_access::test_env::set_var("CARGO_MANIFEST_DIR", dir.path());
        let module: Vec<String> = ["crate", "models", "user"].map(String::from).to_vec();
        assert_eq!(
            compute_target_shape(&module, "Schema", USER_MODEL),
            Some(expected)
        );
    }

    /// Sources this module does not resolve (not a path, a qualified path, a
    /// bare name other than `Model`, a path not rooted at `crate`) fall back
    /// to the circular analysis: `source_of` gives no struct for them.
    #[rstest]
    #[case::not_a_path("[u8; 4]")]
    #[case::qualified_path("<Model as Trait>::Assoc")]
    #[case::bare_other_name("Other")]
    #[case::super_relative("super::legacy::Model")]
    fn unresolved_sources_fall_back(#[case] source: &str) {
        let source: syn::Type = syn::parse_str(source).unwrap();
        let module: Vec<String> = ["crate", "models", "user"].map(String::from).to_vec();
        assert!(source_of(&source, &module, USER_MODEL).is_none());
    }

    /// R31-SM2-01 (round 31): a `schema_type!` the build drops is not the
    /// invocation the `Schema` came from. The removed twin (a `From`-only DTO)
    /// comes first; the live one (`from_model`) must still decide the shape.
    #[rstest]
    #[case::cfg_removed_twin_first("#[cfg(any())]")]
    #[case::cfg_attr_removed_twin_first("#[cfg_attr(all(), cfg(any()))]")]
    fn removed_schema_type_twin_is_not_the_invocation(#[case] twin_attr: &str) {
        let dir = tempfile::TempDir::new().unwrap();
        write_crate(dir.path(), "pub struct Model { pub id: i32 }", "Model", "");
        let user = dir.path().join("src").join("models").join("user.rs");
        let live = std::fs::read_to_string(&user).unwrap();
        std::fs::write(
            &user,
            format!(
                "{twin_attr}\nvespera::schema_type!(Schema from crate::legacy::Model);\n{live}"
            ),
        )
        .unwrap();
        let _manifest = crate::env_access::test_env::set_var("CARGO_MANIFEST_DIR", dir.path());
        let module: Vec<String> = ["crate", "models", "user"].map(String::from).to_vec();
        assert_eq!(
            compute_target_shape(&module, "Schema", USER_MODEL),
            Some(TargetShape::FromModel)
        );
    }
}
